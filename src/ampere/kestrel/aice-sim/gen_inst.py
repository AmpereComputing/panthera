"""The goal of this script is to generate the protobuf enumeration and
the C++ enumeration in the same order. It also numbers the protobuf
enumeration which changed a lot during pathfinding and was annoying to
maintain manually. The output files are aice_opcode_enum.h and opcode.proto
which are meant to be manually inserted in the aice_instruction.h and
aice_stream.proto files.
"""

import argparse
import datetime


def parse_args():
    parser = argparse.ArgumentParser()
    parser.add_argument("input_file", help="Input file name")
    args = parser.parse_args()
    return args


def work():
    args = parse_args()
    opcodes = []
    with open(args.input_file, "r") as fin:
        for line in fin:
            line = line.strip()
            if line:
                opcodes.append(line)

    year = datetime.datetime.now().strftime("%Y")
    with open("aice_opcode_enum.h", "w") as fout:
        print(
            f"""//
// Copyright (c) {year} Ampere Computing. All rights reserved.
// SPDX-License-Identifier: BSD-3-Clause
//
// do not edit. generated by gen_inst.py
#pragma once
#include "ampere/util/enum.h"
make_ns_enum(ampere::kestrel::aice, opcode_t,""",
            file=fout,
        )
        for i, opcode in enumerate(opcodes):
            if i > 0:
                print(",", file=fout)
            print(f"    {opcode}", end="", file=fout)
        print(");", file=fout)

    with open("opcode.proto", "w") as fout:
        print("enum Opcode {", file=fout)
        for i, opcode in enumerate(opcodes):
            print(f"    {opcode}={i};", file=fout)
        print("}", file=fout)


if __name__ == "__main__":
    work()
