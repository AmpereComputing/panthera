class TestReportsMeta(type):
    def __new__(cls, name, bases, dict):
        skip = {
            "SPEC2006int_score",  # workloads/configs
            "SPEC2017fp_score",  # workloads/configs
            "SPEC2017fp_score_gcc10",  # workloads/configs
            "SPEC2017int_score",  # workloads/configs
            "bpu_idle_cycles",  # metrics
            "commit_delay",  # metrics
            "commit_delay_trace",  # metrics
            "drift",  # configs
            "ixu_pipe",  # metrics
            "pmus",  # timeout likely
            "pmus_furiosa",  # timeout likely
            "stall",  # metrics
            "store_forward_predictor",  # metrics
            "tda_bokeh",  # timeout likely
            "tda_sunburst",  # plotly missing on panthera venv (x86)
        }

        def generate_test(path):
            def test(self):
                self.run_report(path)

            return test

        reports = find_reports()
        for report_name, path in reports.items():
            if (
                not likely_standalone(path)
                and report_name not in skip
                and "timeplot" not in report_name
                and "dashboard" not in report_name
            ):
                dict[f"test_{report_name}"] = generate_test(path)

        return type.__new__(cls, name, bases, dict)


