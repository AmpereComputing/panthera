def _test_one_hash_dataparallel(vs,a,b,p,m,vs_len):
    def _h(x):
        return (a*x+b) % p % m
    h_out = [ _h(x) for x in vs ]
    if  len(set(h_out)) == vs_len:
        return True
    if 0:
        d = collections.Counter(h_out)
        mxc = max(d.values())
        print(f'a={a} b={b} p={p} m={m} mxc={mxc}: ', end='')
        for k,v in d.items():
            print(f'{k}:{v} ', end='')
        print()

    return False


def _test_one_hash(vs,a,b,p,m):
    d = array.array('i',[0]*m)
    retval = True
    for v in vs:
        hbin = (a*v+b) % p % m
        c = d[hbin]
        if c != 0 :
            retval=False
        d[hbin]= c+1
    if not retval:
        mxc = max(d)
        print(f'a={a} b={b} p={p} m={m} mxc={mxc}: ', end='')

        for i,v in enumerate(d):
            print(f'{i}:{v} ', end='')
        print()
    return retval


def _find_highest_nonzero_bit_list(arg):
    def find_highest_nonzero_bit(x):
        for i in range(32):
            p = 1 << i
            if p&x:
                return i
        return 32

    m = min([find_highest_nonzero_bit(x) for x in arg])
    return m

def bin32(v):
    return f'{v:032b}'

def next_power_of_2(x):
    assert x!=0
    nlz = bin32(x).index('1')
    assert nlz != 0
    nxt = 1 << (32 - nlz)
    return nxt


@dataclass
class hash_parameters_t:
    """Class for keeping track hash parameters."""
    p: int
    nitems: int
    nbins: int
    a: int
    b: int
    time: int = 0

    def __str__(self):
        s = f'p={self.p} nitems={self.nitems} nbins={self.nbins} a={self.a} b={self.b} time={self.time}'
        return s


def _test_hash(v,verbose):

    def _finish_time_delta(start, s='Elapsed time for previous hash fn search',newline=False):
        delta = time.perf_counter() - start
        if newline:
            print()
        print(f"{s} {delta:0.4f} seconds")
        return delta

    mx = max(v) # largest value
    p = mx # will find next largetst prime
    m = len(v) # of elements in set
    start_time = time.perf_counter()
    mvalues = sorted(set([ m, int(1.5 * m), int(1.75*m), next_power_of_2(m), 2*m, 3*m ]))
    print(f'mvalues={mvalues}')
    for mi,mtry in enumerate(mvalues):
        if verbose:
            print(f"Trying mi={mi} mtry={mtry}")
        p = max(mx,mtry)
        for i in tqdm.tqdm(range(0,10*(mi+1))): # scale primes search by multiplier
            p = sympy.nextprime(p)
            if verbose:
                print(f'\tTrying p={p}')
            alst = range(1,p)
            blst = range(0,p)
            ralst = random.sample(alst,len(alst))
            rblst = random.sample(blst,len(blst))
            for a,b in itertools.product(ralst,rblst):
                if _test_one_hash_dataparallel(v,a,b,p,mtry,m):
                    if verbose:
                        print(f'\t\tmx={mx} p={p} m={m} a={a} b={b} mtry={mtry}')
                    delta = _finish_time_delta(start_time,newline=True)
                    return hash_parameters_t(p, m, mtry, a, b, delta)
        _finish_time_delta(start_time,"prime iteration took")
    delta = _finish_time_delta(start_time)
    return hash_parameters_t(0, m, 0, 0, 0, delta)

