"""Generate pmu.h from pmu.txt as part of build process"""

import argparse
import datetime
import os
import re


def parse_args():
    parser = argparse.ArgumentParser()
    parser.add_argument("input_file_name", nargs=1, help="Input file name")
    args = parser.parse_args()
    return args


def work():
    args = parse_args()

    with open("pmu.h", "w") as hout:
        year = datetime.date.today().year
        recreate = """
//
// Create the src/ampere/archx/pmu.txt file by running this above the RTL directory:
//  % sed -rn "s/^parameter CPU_PMU_([A-Z0-9_]+)\\s+=\\s+16'h([0-9A-F]{4});"'$'"/\\1 \\2/p" rtl/Subsystems/Cpu/Common/PmuEvents.svh > pmu.txt
// Then copy the pmu.txt PATH-TO-PANTHERA/src/ampere/archx
//      Note: Events in the ID space 0xE*** are Panthera-only events, and not tracked in RTL. When generating the pmu.txt from the above command,
//            carry over these amendments from the old pmu.txt file.
// Scripts in archx will recreate pmu.h from that.
//
"""

        hheader = f"""
//
// Copyright (c) 2018-{year} Ampere Computing. All rights reserved.
// SPDX-License-Identifier: BSD-3-Clause
//
// AUTOGENERATED DO NOT EDIT
// AUTOGENERATED DO NOT EDIT
// AUTOGENERATED DO NOT EDIT
{recreate}
#pragma once

#include "ampere/util/enum.h"

make_ns_enum(ampere::archx, PMU,"""
        print(hheader, file=hout)
        pmus = []
        with open(args.input_file_name[0], "r") as fin:
            for line in fin:
                line = line.strip()
                chunks = line.split()
                pmu_name = chunks[0]
                pmu_number = int(f"0x{chunks[1]}", 16)
                pmus.append((pmu_number, pmu_name))

        pmus = sorted(pmus, key=lambda x: x[0])
        width = max([len(name) for _, name in pmus])
        for index, (pmu_number, pmu_name) in enumerate(pmus):
            ending = "," if (index + 1) < len(pmus) else ""
            print(f"    {pmu_name + ' ' * (width - len(pmu_name))} = {pmu_number:#06x}{ending}", file=hout)

        print(");", file=hout)


if __name__ == "__main__":
    work()
