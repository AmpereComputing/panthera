def run(cmd, shell=False, logger=logging, output=None):
    """Log and run a command and error if it returns a nonzero return code"""
    if not shell and isinstance(cmd, (str, bytes)):
        cmd = shlex.split(cmd)
        logger.info("Running: " + " ".join(cmd))
    else:
        logger.info(f"Running: {cmd}")
    if output:
        f = open(output, "a")
        logger.info(f"Logging output to {output}")
        proc = subprocess.run(cmd, shell=shell, stdout=f, stderr=f)
        f.close()
    else:
        proc = subprocess.run(cmd, shell=shell)
    proc.check_returncode()


def collect_simpoints(cmdline_json, kernel, bbv_plugin, tracing_plugin, bbv_interval, warmup_instrs, capture_traces):
    benchmark = cmdline_json["benchmark"]
    cmdline = cmdline_json["cmdline"]
    cmdline_num = cmdline_json["cmdline_num"]
    disk_image = cmdline_json["disk_image"]
    init_script = cmdline_json["init_script"]

    base_dir = f"{benchmark}-{cmdline_num}"
    os.makedirs(base_dir)

    logger = logging.getLogger(f"{benchmark}-{cmdline_num}")
    logger.setLevel(logging.DEBUG)
    handler = logging.FileHandler(os.path.join(base_dir, f"{benchmark}-{cmdline_num}.log"))
    formatter = logging.Formatter("%(asctime)s - %(name)s - %(levelname)s - %(message)s")
    handler.setFormatter(formatter)
    logger.addHandler(handler)

    qemu_base_cmd = (
        "qemu-system-aarch64"
        " -smp 1"
        " -m 4G"
        " -M virt"
        " -cpu cortex-a57"
        f" -kernel {kernel}"
        f' -append "console=ttyAMA0 root=/dev/vda rw perf.semihosting init={init_script} earlycon=smh"'
        f" -drive if=none,file={disk_image},id=hd0,format=qcow2"
        " -device virtio-blk-pci,drive=hd0"
        " -nographic"
        " -semihosting"
        " -icount 0"
    )
    profile_comm = os.path.basename(cmdline.split()[0])
    checkpoint_interval = 10000000000  # Does this ever need to be changed?
    bbv_filename = os.path.join(base_dir, "vectors.bbv")
    generation_json = os.path.join(base_dir, "bbv_generation.json")
    generation_log = os.path.join(base_dir, "bbv_generation.log")
    qemu_bbv_cmd = (
        f"{qemu_base_cmd}"
        f" -plugin {bbv_plugin},"
        'arg="'
        f"--profile-comm {profile_comm}"
        f" --bbv-interval {bbv_interval}"
        f" --checkpoint-interval {checkpoint_interval}"
        f" --bbv-filename {bbv_filename}"
        f' --generation-log {generation_json}"'
        f" -d plugin"
        f" -D {generation_log}"
    )
    run(qemu_bbv_cmd, shell=True, logger=logger, output=os.path.join(base_dir, "bbv_collection.log"))

    trace_base = os.path.join(base_dir, f"{benchmark}-{cmdline_num}")
    capture_traces_cmd = (
        f"{capture_traces}"
        f" --generation-log {generation_json}"
        f" --qemu-command '{qemu_base_cmd}'"
        f" --plugin {tracing_plugin}"
        f" --trace-base {trace_base}"
        f" --start-measuring-after-online-warmup-instructions {warmup_instrs}"
    )

    run(capture_traces_cmd, shell=True, logger=logger, output=os.path.join(base_dir, "capture_traces.log"))


def main():
    parser = argparse.ArgumentParser(
        description="Read JSON file representing SPEC workloads and generate simpoints for them"
    )
    parser.add_argument(
        "--json",
        help="File to read JSON representation of workloads from (generated by 00_generate_disk_images.py)",
        type=open,
        required=True,
    )
    parser.add_argument("--kernel", help="Path to kernel image to use", type=open, required=True)
    parser.add_argument("--bbv-plugin", help="Path to QEMU BBV plugin", type=open, required=True)
    parser.add_argument("--bbv-interval", help="BBV interval length (in instructions)", type=int, required=True)
    parser.add_argument(
        "--warmup-instrs",
        help="The number of instructions to collect before the beginning of the specified interval",
        type=int,
        required=True,
    )
    parser.add_argument("--tracing-plugin", help="Path to QEMU instruction tracing plugin", type=open, required=True)
    parser.add_argument(
        "--capture-traces",
        help="Full path to src/ampere/tracing_tools/scripts/capture_traces.py",
        type=open,
        required=True,
    )
    args = parser.parse_args()

    if os.geteuid() == 0:
        print("This script does not need to be run as root (or sudo)!")
        sys.exit(1)

    json_cmdlines = json.load(args.json)

    threads = []
    for c in json_cmdlines:
        benchmark = c["benchmark"]
        cmdline_num = c["cmdline_num"]
        t = threading.Thread(
            target=collect_simpoints,
            name=f"{benchmark}_{cmdline_num}",
            args=(),
            kwargs=dict(
                cmdline_json=c,
                kernel=args.kernel.name,
                bbv_plugin=args.bbv_plugin.name,
                tracing_plugin=args.tracing_plugin.name,
                bbv_interval=args.bbv_interval,
                warmup_instrs=args.warmup_instrs,
                capture_traces=args.capture_traces.name,
            ),
        )
        threads.append(t)
        t.start()

    for t in threads:
        t.join()
        if t.is_alive():
            raise Exception(f"Failed to join thread {t.name}")


if __name__ == "__main__":
    try:
        main()
    except Exception as e:
        logging.shutdown()
        raise
    logging.shutdown()
