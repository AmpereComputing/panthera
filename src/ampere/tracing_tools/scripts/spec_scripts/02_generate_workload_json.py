import argparse
import json
import os
import sys


def main():
    parser = argparse.ArgumentParser(
        description="Read JSON file representing SPEC workloads and generate workloads.json files for th em"
    )
    parser.add_argument(
        "--json",
        help="File to read JSON representation of workloads from (generated by 00_generate_disk_images.py)",
        type=open,
        required=True,
    )
    parser.add_argument(
        "--suite", help='Value for "suite" entry in the resulting workloads-json file', type=str, required=True
    )
    parser.add_argument(
        "--workloads-json", help="Where to write workloads.json", type=argparse.FileType("w"), required=True
    )
    args = parser.parse_args()

    if os.geteuid() == 0:
        print("This script does not need to be run as root (or sudo)!")
        sys.exit(1)

    json_cmdlines = json.load(args.json)

    # Loop through once to get total instruction counts for weight calculations
    benchmark_instructions = {}
    for c in json_cmdlines:
        benchmark = c["benchmark"]
        cmdline_num = c["cmdline_num"]
        manifest_path = os.path.join(f"{benchmark}-{cmdline_num}", "manifest.json")
        with open(manifest_path) as manifest_file:
            manifest = json.load(manifest_file)

        cmd_instruction_count = int(manifest["collection_methodology"]["simpoint_total_instructions"])
        if benchmark in benchmark_instructions:
            benchmark_instructions[benchmark] += cmd_instruction_count
        else:
            benchmark_instructions[benchmark] = cmd_instruction_count

    # Loop through again to calculate new weights and write to manifest
    workloads = []
    for c in json_cmdlines:
        benchmark = c["benchmark"]
        cmdline_num = c["cmdline_num"]
        manifest_path = os.path.join(f"{benchmark}-{cmdline_num}", "manifest.json")
        with open(manifest_path) as manifest_file:
            manifest = json.load(manifest_file)

        cmd_instruction_count = int(manifest["collection_methodology"]["simpoint_total_instructions"])
        for stream in manifest["instruction_streams"]["threads"]:
            stream_id = stream["id"]
            workloads.append(
                {
                    "name": f"{benchmark}_{cmdline_num}_{stream_id}",
                    "workload": benchmark,
                    "suite": args.suite,
                    "weight": str(float(stream["weight"]) * cmd_instruction_count / benchmark_instructions[benchmark]),
                    "file": os.path.join(f"{benchmark}-{cmdline_num}", stream["file"]),
                    "warmup_instrs": stream["warmup_instrs"],
                    "sha256sum": stream["sha256sum"],
                }
            )

    json.dump(workloads, args.workloads_json, indent=4)


if __name__ == "__main__":
    main()
